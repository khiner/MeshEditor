struct MeshPipelines {
    explicit MeshPipelines(mtl::LibraryCache &);
    const mtl::ComputePipeline &operator[](MeshPass pass) const;
    void PrewarmAsync();

    mtl::LibraryCache &Libraries;
    mutable std::mutex Mutex;
    mutable std::array<std::optional<mtl::ComputePipeline>, size_t(MeshPass::Count)> Pipelines;
    std::jthread PrewarmWorker;
};

// The registry's mesh pipelines, created on first use, where each pass compiles when first requested.
MeshPipelines &GetMeshPipelines(state::Registry &);
// The pipelines a registry whose meshes have shaded already holds.
const MeshPipelines &GetMeshPipelines(const state::Registry &);
